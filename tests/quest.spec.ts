test('unfinished model and hint usage survive reload; old discoveries migrate', async ({ page }) => {
  await page.addInitScript(() => {
    if (!localStorage.getItem('fraction-lab-stage-a-v1')) localStorage.setItem('fraction-lab-stage-a-v1',JSON.stringify(['split','line']));
  });
  await page.goto('/');
  await expect(page.getByText('50 XP', { exact: true })).toBeVisible();
  await page.locator('.world-card').nth(4).click();
  await page.getByRole('slider', { name: 'Неизвестното x' }).fill('14');
  await page.getByRole('button', { name: 'Нуждая се от насока' }).click();
  await page.reload();
  await expect(page.getByRole('slider', { name: 'Неизвестното x' })).toHaveValue('14');
  await expect(page.locator('.hint')).toBeVisible();
  await page.getByRole('slider', { name: 'Неизвестното x' }).fill('18');
  await check(page);
  await expect(page.getByText('80 XP', { exact: true })).toBeVisible();
});
test('export and import restore progress and reject malformed files safely', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'За родителя', exact: true }).click();
  const valid = JSON.stringify({ version: 2, discoveries: ['split'], results: { 'balance-missing': { assisted: false, attempts: 2, completedAt: Date.now() } }, currentMission: null, drafts: {} });
  const upload = page.getByLabel('Резервно копие на напредъка');
  await upload.setInputFiles({ name: 'progress.json', mimeType: 'application/json', buffer: Buffer.from(valid) });
  await expect(page.getByText('75 XP', { exact: true })).toBeVisible();
  await upload.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{bad') });
  await expect(page.getByText('Файлът не е валидно резервно копие. Текущият напредък е запазен.')).toBeVisible();
  await expect(page.getByText('75 XP', { exact: true })).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Изтегли напредъка' }).click();
  expect((await download).suggestedFilename()).toBe('fraction-lab-progress.json');
});
test('advanced missions work on touch and narrow screens with reduced motion', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, reducedMotion: 'reduce' });
  const page = await context.newPage();
  await page.goto('/');
  await page.locator('.world-card').nth(5).tap();
  const firstPlus = page.getByRole('button', { name: 'Първи разход: увеличи', exact: true });
  for (let i = 0; i < 8; i++) await firstPlus.tap();
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: 'Втори разход от остатъка: увеличи', exact: true }).tap();
  await page.getByRole('button', { name: 'Провери модела' }).tap();
  await expect(page.locator('.quest-feedback.success')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/quest-mobile-remainder.png', fullPage: true });
  await page.getByRole('button', { name: 'Към следващия свят' }).tap();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/quest-mobile-reverse.png', fullPage: true });
  await context.close();
});
