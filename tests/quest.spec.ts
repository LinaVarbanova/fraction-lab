import { expect, test, type Page } from '@playwright/test';
async function check(page: Page) {
  await page.getByRole('button', { name: 'Провери модела' }).click();
  await expect(page.locator('.quest-feedback.success')).toBeVisible();
}
async function enter(page: Page, title: string) {
  await page.getByRole('button', { name: 'Карта на уменията', exact: true }).click();
  await page.getByRole('button', { name: new RegExp(title) }).click();
  await expect(page.getByRole('heading', { level: 2, name: title, exact: true })).toBeVisible();
}
